/* ---------------------------------- Equal --------------------------------- */
// Apakah setara atau tidak?
// 1. Loose Equal | Double Equal (==)
console.log(1 == 1);
console.log(1 == 5);
console.log(1 == "1");
console.log(1 == {});

// 2. Strict Equal | Triple Equal (===)
console.log(1 === 1);
console.log(1 === 5);
console.log(1 === "1");
console.log(1 === {});

/* -------------------------------- Not Equal ------------------------------- */
// Apakah TIDAK setara?
// 1. Loose Not Equal (!=)
console.log(1 != 10);
console.log(1 != 1);
console.log(1 != "1");

// 2. Strict Not Equal (!==)
console.log(1 !== 10);
console.log(1 !== 1);
console.log(1 !== "1");

/* ------------------------------ Greater Than ------------------------------ */
// Apakah lebih besar?
// >
console.log(1 > 0);
console.log(1 > 1);

/* -------------------------- Greater Than Or Equal ------------------------- */
// Apakah lebih besar ATAU setara?
// >=
console.log(1 >= 0);
console.log(1 >= 1);

