export function addTwoNumber(num1, num2) {
  return num1 + num2;
}

export function multiplyTwoNumber(num1, num2) {
  return num1 * num2;
}

export function divideTwoNumber(num1, num2) {
  return num1 / num2;
}

export default function subtractTwoNumber(num1, num2) {
  return num1 - num2;
}
